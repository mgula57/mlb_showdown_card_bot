"""Who is behind a web request, beyond the signed-in account: a browser-level anonymous id
(kept in the visitor's localStorage) and a per-tab session id (sessionStorage). Both are random
UUIDs generated by the frontend (`frontend/src/analytics/clientIds.ts`), sent as headers, and
stored next to `user_id` on the request logs so anonymous visitors can be counted and a
visitor's activity before signing in can be tied to the account they sign in with.
"""

import re
from dataclasses import dataclass
from typing import ClassVar, Mapping, Optional

_UUID = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$", re.I)


@dataclass(frozen=True)
class ClientContext:
    anon_id: Optional[str] = None
    session_id: Optional[str] = None

    ANON_ID_HEADER: ClassVar[str] = 'X-Showdown-Anon-Id'
    SESSION_ID_HEADER: ClassVar[str] = 'X-Showdown-Session-Id'

    @staticmethod
    def clean_id(value: Optional[str]) -> Optional[str]:
        """The value if it's a UUID, else None: these come from the client, so nothing else is stored."""
        value = (value or '').strip()
        return value.lower() if _UUID.match(value) else None

    @classmethod
    def from_headers(cls, headers: Mapping[str, str]) -> 'ClientContext':
        return cls(
            anon_id=cls.clean_id(headers.get(cls.ANON_ID_HEADER)),
            session_id=cls.clean_id(headers.get(cls.SESSION_ID_HEADER)),
        )

    def as_columns(self) -> dict[str, Optional[str]]:
        return {'anon_id': self.anon_id, 'session_id': self.session_id}


EMPTY_CLIENT_CONTEXT = ClientContext()
